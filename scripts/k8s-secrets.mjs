#!/usr/bin/env node
// Generates the Kubernetes Secrets for the self-hosted MedLink stack (k8s/).
// Every value is random and created on YOUR machine: nothing is stored in Git (US-45).
//
//   node scripts/k8s-secrets.mjs > k8s/secrets.local.yaml
//   kubectl apply -f k8s/secrets.local.yaml
//
// Optional: real SMTP for the app's own e-mails (confirmations, reminders). Without it, every
// e-mail (sign-up codes too) goes to Mailpit: http://127.0.0.1:8025 on the demo cluster.
//   SMTP_HOST=smtp.gmail.com SMTP_PORT=465 SMTP_USER=... SMTP_PASS=... node scripts/k8s-secrets.mjs
// k8s/secrets.local.yaml is in .gitignore. Re-running creates NEW keys: only do it on a fresh cluster.
import { createHmac, randomBytes } from "node:crypto";

const rand = (n = 32) => randomBytes(n).toString("hex");
const b64url = (v) =>
  Buffer.from(typeof v === "string" ? v : JSON.stringify(v)).toString("base64url");

function jwt(secret, role) {
  const iat = Math.floor(Date.now() / 1000);
  const head = b64url({ alg: "HS256", typ: "JWT" });
  const body = b64url({ role, iss: "supabase", iat, exp: iat + 10 * 365 * 24 * 3600 });
  const sig = createHmac("sha256", secret).update(`${head}.${body}`).digest("base64url");
  return `${head}.${body}.${sig}`;
}

const jwtSecret = rand(32);
const anonKey = jwt(jwtSecret, "anon");
const serviceKey = jwt(jwtSecret, "service_role");
const env = process.env;

const secret = (name, data) =>
  [
    "---",
    "apiVersion: v1",
    "kind: Secret",
    "metadata:",
    `  name: ${name}`,
    "  namespace: medlink",
    "type: Opaque",
    "stringData:",
    ...Object.entries(data).map(([k, v]) =>
      String(v).includes("\n")
        ? `  ${k}: |\n${String(v)
            .trimEnd()
            .split("\n")
            .map((l) => `    ${l}`)
            .join("\n")}`
        : `  ${k}: ${JSON.stringify(String(v))}`,
    ),
  ].join("\n");

const out = [
  "# GENERATED by scripts/k8s-secrets.mjs. Do not commit (see .gitignore).",
  // Root key of pgsodium / Supabase Vault (medical_data_key is encrypted with it, US-43).
  // The SAME key is mounted on both database copies, so the standby can decrypt after a failover.
  secret("medlink-db-keys", {
    "pgsodium_root.key": rand(32),
    "getkey.sh": "#!/bin/sh\ncat /projected/pgsodium_root.key\n",
  }),
  // Passwords of the Supabase service roles, and the JWT keys shared by auth, REST and storage.
  secret("medlink-supabase", {
    JWT_SECRET: jwtSecret,
    ANON_KEY: anonKey,
    SERVICE_ROLE_KEY: serviceKey,
    SUPABASE_ADMIN_PASSWORD: rand(16),
    AUTH_DB_PASSWORD: rand(16),
    STORAGE_DB_PASSWORD: rand(16),
    AUTHENTICATOR_PASSWORD: rand(16),
  }),
  // Server-side settings of the MedLink backend.
  secret("medlink-app", {
    SUPABASE_PUBLISHABLE_KEY: anonKey,
    SUPABASE_SERVICE_ROLE_KEY: serviceKey,
    CRON_SECRET: rand(24),
    SMTP_HOST: env.SMTP_HOST ?? "mailpit",
    SMTP_PORT: env.SMTP_PORT ?? "1025",
    SMTP_USER: env.SMTP_USER ?? "medlink",
    SMTP_PASS: env.SMTP_PASS ?? "mailpit",
    // Mailpit has no TLS; a real SMTP server keeps TLS required.
    SMTP_INSECURE: env.SMTP_HOST ? "0" : "1",
    // Auth service (GoTrue): no login for Mailpit (Go refuses to send a password without TLS).
    AUTH_SMTP_USER: env.SMTP_HOST ? (env.SMTP_USER ?? "") : "",
    AUTH_SMTP_PASS: env.SMTP_HOST ? (env.SMTP_PASS ?? "") : "",
    SMTP_FROM: env.SMTP_FROM ?? "MedLink <no-reply@medlink.local>",
    AI_API_KEY: env.AI_API_KEY ?? "",
  }),
];
process.stdout.write(out.join("\n") + "\n");
